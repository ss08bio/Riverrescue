function Script2()
{
  var music = window.riverRescueMusic;

if (!music) {
    music = new Audio("./musik.mp3");
    music.loop = true;
    music.volume = 0.4;
    window.riverRescueMusic = music;
}

music.play().catch(function(error) {
    console.log("Musik gagal diputar:", error);
});
}

